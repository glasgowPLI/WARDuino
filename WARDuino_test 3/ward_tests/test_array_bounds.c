// 数组边界测试
void _start() {
    // 一维数组
    int arr1d[10];
    
    // 边界内访问
    for (int i = 0; i < 10; i++) {
        arr1d[i] = i * 2;
    }
    
    // 边界外访问
    arr1d[-1] = -1;  // 下界溢出
    arr1d[10] = 20;  // 上界溢出
    arr1d[15] = 30;  // 明显溢出
    
    // 多维数组
    int arr2d[5][5];
    
    // 正常访问
    for (int i = 0; i < 5; i++) {
        for (int j = 0; j < 5; j++) {
            arr2d[i][j] = i + j;
        }
    }
    
    // 多维数组越界
    arr2d[5][0] = 99;  // 第一维越界
    arr2d[0][5] = 88;  // 第二维越界
}
